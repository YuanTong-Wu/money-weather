# Morningstar categories (fundProfile.categoryName) -> nongeo category
def category_of_morningstar(cat):
    c = (cat or '').lower()
    if not c:
        return None
    if 'digital asset' in c or 'crypto' in c:
        return 'crypto'
    if 'money market' in c or 'ultrashort' in c or 'single currency' in c or 'currency' in c:
        return 'cash'
    if 'commodit' in c or 'precious metals' in c:
        return 'commodities'
    if any(k in c for k in ('bond', 'government', 'treasury', 'muni', 'corporate', 'high yield', 'bank loan',
                             'inflation', 'mortgage', 'securitized', 'multisector', 'credit', 'fixed income',
                             'target maturity', 'preferred')):
        return 'bonds'
    if any(k in c for k in ('technology', 'health', 'financial', 'real estate', 'utilities', 'industrials',
                             'communications', 'consumer', 'energy', 'infrastructure', 'natural resources',
                             'miscellaneous sector', 'equity energy', 'reit')):
        return 'sector'
    return None

